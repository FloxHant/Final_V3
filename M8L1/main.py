@bot.message_handler(commands=["start"])
def handle_start(message):
    bot.send_message(message.chat.id, "Привет! Я бот для просмотра расписания. Выберите 'Расписание' в меню.", reply_markup=main_menu())

@bot.message_handler(func=lambda m: True)
def handle_message(message):
    text = message.text
    chat_id = message.chat.id

    if text == "Расписание":
        bot.send_message(chat_id, "Выберите день недели:", reply_markup=days_menu())

    elif text in ["Понедельник", "Вторник", "Среда", "Четверг", "Пятница"]:
        user_states[chat_id] = {'day': text}
        bot.send_message(chat_id, f"Вы выбрали {text}. Теперь выберите класс:", reply_markup=classes_menu())

    elif text.startswith("Класса "):
        klass = text.replace("Класса ", "")
        day = user_states.get(chat_id, {}).get('day')
        if day:
            lessons = schedule.get(day, {}).get(klass, "Расписание отсутствует.")
            bot.send_message(chat_id, f"Расписание для {klass} Класса на {day}:\n\n{lessons}", reply_markup=back_button())
        else:
            bot.send_message(chat_id, "Пожалуйста, сначала выберите день недели:")

    elif text == "Назад":
        bot.send_message(chat_id, "Вы вернулись в главное меню:", reply_markup=main_menu())

    elif text == "Помощь":
        bot.send_message(chat_id, "Это бот для просмотра школьного расписания. Используйте меню для навигации. Если что-то случилось или поломка бота наишите нам на почту: --- ")

    else:
        bot.send_message(chat_id, "Я не понял команду. Пожалуйста, используйте меню:")

